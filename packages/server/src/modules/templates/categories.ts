/**
 * The catalog's category vocabulary, and how a source's free-form tags map
 * onto it.
 *
 * A blueprint declares tags, not a category, and the first one used to become
 * the category verbatim. On the public blueprints catalog that produced **209
 * categories for 436 templates, 125 of them holding a single entry** —
 * "File-manager", "Whatsapp", "Erp" — which is not a filter, it is a list of
 * templates spelled differently. The gallery's category rail was unusable and
 * so was the landing catalog's grouping.
 *
 * So tags are resolved against the fifteen categories the built-in catalog
 * already uses. The tag list is read in order and the first tag that maps
 * wins, which is why the map deliberately does NOT contain the generic tags
 * every entry carries (`self-hosted`, `open-source`, `web`, `app`): they would
 * swallow everything they precede. Nothing recognizable falls through to
 * `Community`, which stays visible rather than being hidden inside a real
 * category.
 */

