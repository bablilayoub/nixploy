const normalizeTag = (tag: string): string =>
	tag
		.trim()
		.toLowerCase()
		.replace(/[\s_]+/g, "-")
		.replace(/^#/, "");

/**
 * The category for a set of source tags: the first tag that maps to one of
 * {@link TEMPLATE_CATEGORIES}, else {@link FALLBACK_CATEGORY}. Order matters —
 * a template tagged `["media", "storage"]` is Media, not Storage.
 */
export function categoryFromTags(tags: readonly string[]): string {
	for (const tag of tags) {
		const mapped = TAG_CATEGORY[normalizeTag(tag)];
		if (mapped) return mapped;
	}
	return FALLBACK_CATEGORY;
}
